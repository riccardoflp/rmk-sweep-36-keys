"""Generates tests/zmk_parity.toml from the ZMK keymap this port comes from.

Every key on every layer becomes a simulator case that taps it and expects
the reports ZMK would send, so `scripts/test_keymap.sh` catches any key whose
RMK binding drifts from the ZMK original.

    python scripts/gen_zmk_parity.py path/to/swweeep.keymap > tests/zmk_parity.toml
"""

import json
import re
import sys

# Layout position -> (row, col) in RMK's unified matrix
POS = [(r, c) for r in range(3) for c in range(10)] + [(3, 2), (3, 3), (3, 4), (3, 5), (3, 6), (3, 7)]
# Key held to reach each layer
ACTIVATOR = {"nav": (3, 4), "mouse": (3, 7), "sym": (3, 6), "func": (3, 2), "num": (3, 5), "adj": (0, 9)}
# Positions where the port deliberately differs from ZMK, see README
SKIP = {("adj", 0): "ClearEeprom, which would wipe storage", ("adj", 4): "bootloader", ("adj", 5): "bootloader"}

PLAIN = {
    "SEMI": "Semicolon", "COMMA": "Comma", "DOT": "Dot", "FSLH": "Slash", "ESC": "Escape", "SPACE": "Space",
    "TAB": "Tab", "ENTER": "Enter", "BSPC": "Backspace", "DEL": "Delete", "HOME": "Home", "UP": "Up",
    "END": "End", "PG_UP": "PageUp", "PG_DN": "PageDown", "LEFT": "Left", "DOWN": "Down", "RIGHT": "Right",
    "CAPS": "CapsLock", "KP_NUM": "NumLock", "INS": "Insert", "K_CMENU": "Application", "K_UNDO": "Undo",
    "K_CUT": "Cut", "K_COPY": "Copy", "K_PASTE": "Paste", "SLCK": "ScrollLock", "PSCRN": "PrintScreen",
    "GRAVE": "Grave", "SQT": "Quote", "EQUAL": "Equal", "LBKT": "LeftBracket", "RBKT": "RightBracket",
    "MINUS": "Minus", "BSLH": "Backslash",
}
PLAIN.update({f"N{i}": f"Kc{i}" for i in range(10)})
PLAIN.update({f"F{i}": f"F{i}" for i in range(1, 13)})
PLAIN.update({c: c for c in "ABCDEFGHIJKLMNOPQRSTUVWXYZ"})
SHIFTED = {
    "DQT": "Quote", "LBRC": "LeftBracket", "RBRC": "RightBracket", "AT": "Kc2", "TILDE": "Grave", "AMPS": "Kc7",
    "EXCL": "Kc1", "PIPE": "Backslash", "PRCNT": "Kc5", "DLLR": "Kc4", "LPAR": "Kc9", "RPAR": "Kc0",
    "UNDER": "Minus", "HASH": "Kc3", "CARET": "Kc6", "LT": "Comma", "GT": "Dot", "ASTRK": "Kc8", "PLUS": "Equal",
}
MODS = {"LGUI": "LGui", "LALT": "LAlt", "LCTL": "LCtrl", "LSHIFT": "LShift", "RSHIFT": "RShift", "RCTL": "RCtrl",
        "RGUI": "RGui"}
# K_REDO is Ctrl+Shift+Z: RMK's `Again` keycode is a Repeat key
SHORTCUTS = {"K_REDO": ["LCtrl", "LShift", "Z"]}
# C_PAUSE has no RMK keycode and is sent as Play/Pause
CONSUMER = {"C_RW": "MediaRewind", "C_PAUSE": "MediaPlayPause", "C_FF": "MediaFastForward",
            "C_VOL_UP": "AudioVolUp", "C_VOL_DN": "AudioVolDown", "C_PREV": "MediaPrevTrack",
            "C_PLAY_PAUSE": "MediaPlayPause", "C_NEXT": "MediaNextTrack", "C_MUTE": "AudioMute"}
BUTTONS = {"LCLK": 1, "RCLK": 2, "MCLK": 4, "MB4": 8, "MB5": 16}
# Signs follow ZMK's pointing.h; RMK moves 5 px or 1 wheel unit per step
MOTION = {"MOVE_UP": {"y": -5}, "MOVE_DOWN": {"y": 5}, "MOVE_LEFT": {"x": -5}, "MOVE_RIGHT": {"x": 5},
          "SCRL_UP": {"wheel": 1}, "SCRL_DOWN": {"wheel": -1}, "SCRL_LEFT": {"pan": -1}, "SCRL_RIGHT": {"pan": 1}}
MACROS = {
    "sqm": [["Quote"], [], ["Space"], [], []],
    "dqm": [["LShift", "Quote"], ["LShift"], ["Space"], [], []],
    "bm": [["Grave"], [], ["Space"], [], []],
    "lca_tab": [["LCtrl"], ["LCtrl", "LAlt"], ["LCtrl", "LAlt", "Tab"], ["LCtrl", "LAlt"], ["LCtrl"], []],
}


def key(k):
    if k in PLAIN:
        return [PLAIN[k]]
    if k in SHIFTED:
        return ["LShift", SHIFTED[k]]
    if k in SHORTCUTS:
        return SHORTCUTS[k]
    return [MODS[k]]


def expect(binding):
    """Reports a quick tap of a ZMK binding sends."""
    kind, args = binding[0], binding[1:]
    if kind == "kp" and args[0] in CONSUMER:
        return [{"consumer": [CONSUMER[args[0]]]}, {"consumer": []}]
    if kind == "kp":
        return [key(args[0]), []]
    if kind in ("lt", "hr"):
        return [key(args[1]), []]
    if kind == "mkp":
        return [{"mouse": {"buttons": BUTTONS[args[0]]}}, {"mouse": {}}]
    if kind in ("mmv", "msc"):
        return [{"mouse": MOTION[args[0]]}, {"mouse": {}}]
    if kind in MACROS:
        return MACROS[kind]
    if kind in ("bt", "out", "ext_power"):
        return []
    raise KeyError(binding)


def toml(v):
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{k} = {toml(x)}" for k, x in v.items()) + " }"
    if isinstance(v, list):
        return "[" + ", ".join(toml(x) for x in v) + "]"
    return json.dumps(v)


def case(name, steps, expected):
    return f'\n[[test]]\nname = "{name}"\nsteps = {toml(steps)}\nexpect = {toml(expected)}\n'


def main():
    src = re.sub(r"//[^\n]*", "", open(sys.argv[1]).read())
    layers = [(name, [b.split() for b in body.split("&")[1:]])
              for name, body in re.findall(r"(\w+)_layer\s*\{\s*bindings\s*=\s*<(.*?)>;", src, re.S)]
    base = layers[0][1]

    out = ["# Generated by scripts/gen_zmk_parity.py from the ZMK keymap; do not edit.\n"
           'keyboard = "boards/sweep36.toml"\n']
    for name, bindings in layers:
        act = ACTIVATOR.get(name)
        for p, b in enumerate(bindings):
            if act == POS[p] or (name, p) in SKIP:
                continue
            b = base[p] if b[0] == "trans" else b
            tap = {"tap": {"pos": list(POS[p]), "duration": 20}}
            steps = [tap, {"delay": 300}] if act is None else \
                [{"press": list(act)}, {"delay": 250}, tap, {"release": list(act)}, {"delay": 300}]
            label = re.sub(r"[^a-z0-9_]", "_", f"{name}_{p:02d}_{'_'.join(b).lower()}")
            out.append(case(label, steps, expect(b)))

    # Caps Word combo on keys 13 and 16, on every layer but ADJ
    for name, act in ACTIVATOR.items():
        if name == "adj":
            continue
        steps = [{"press": list(act)}, {"delay": 250}, {"press": [1, 3]}, {"delay": 10}, {"press": [1, 6]},
                 {"delay": 20}, {"release": [1, 3]}, {"release": [1, 6]}, {"release": list(act)},
                 {"delay": 300}, {"tap": {"pos": [2, 4], "duration": 20}}]
        out.append(case(f"capsword_combo_{name}", steps, [["LShift", "B"], []]))

    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
